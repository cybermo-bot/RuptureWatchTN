'use client';

import { Building2, Hospital, Landmark, Search, Stethoscope, Store, Truck, Users, type LucideIcon } from 'lucide-react';
import Image from 'next/image';
import Link from 'next/link';
import { useFormStatus } from 'react-dom';
import { signInAsDemoRole } from '@/app/actions/auth';
import previews from '@/public/previews/manifest.json';
import { DEMO_ROLES, type DemoRole, type RoleGroup, type RoleIcon } from '@/lib/demo/roles';
import { t } from '@/lib/i18n';

// "Choisissez un rôle": the one-click demo roles as tiles, in three groups, each with its icon,
// one line on what it does and a preview of its screen (a screenshot regenerated by
// `npm run previews:build`, never drawn by hand). The public side needs no role: a plain link.

const ICONS: Record<RoleIcon | 'public', LucideIcon> = {
  pharmacy: Store,
  hospital: Hospital,
  wholesaler: Truck,
  ministry: Landmark,
  central: Building2,
  order: Users,
  prescriber: Stethoscope,
  public: Search,
};

const GROUPS: RoleGroup[] = ['terrain', 'pilotage', 'public'];
const HAS_PREVIEW = new Set<string>(previews.previews);

function Preview({ name, label, phone }: { name: string; label: string; phone: boolean }) {
  if (!HAS_PREVIEW.has(name)) return null;
  return (
    <span className="relative hidden aspect-[16/10] overflow-hidden border-b border-line bg-surface-subtle sm:block">
      <Image
        src={`/previews/${name}.jpg`}
        alt={t('core.home.previewAlt', { role: label })}
        width={phone ? 360 : 640}
        height={phone ? 780 : 400}
        sizes={phone ? '160px' : '(min-width: 1024px) 22rem, 90vw'}
        className={
          phone
            ? 'absolute start-1/2 top-3 w-[42%] -translate-x-1/2 rounded-t-md border border-b-0 border-line shadow-[0_1px_0_var(--line)] rtl:translate-x-1/2'
            : 'absolute inset-x-3 top-3 w-[calc(100%-1.5rem)] rounded-t-md border border-b-0 border-line'
        }
      />
    </span>
  );
}

function TileBody({ icon, label, hint }: { icon: LucideIcon; label: string; hint: string }) {
  const Icon = icon;
  return (
    <span className="flex flex-1 items-start gap-3 p-4">
      <span className="inline-flex size-9 shrink-0 items-center justify-center rounded-md bg-surface-subtle text-brand">
        <Icon size={18} strokeWidth={1.75} aria-hidden="true" />
      </span>
      <span className="flex min-w-0 flex-col gap-0.5">
        <span className="font-semibold text-ink">{label}</span>
        <span className="text-sm text-ink-muted">{hint}</span>
      </span>
    </span>
  );
}

const TILE =
  'group panel flex h-full w-full flex-col overflow-hidden text-start no-underline transition-colors duration-150 hover:border-ink-muted disabled:cursor-wait';

function RoleTile({ role }: { role: DemoRole }) {
  const { pending, data } = useFormStatus();
  const chosen = pending ? String(data?.get('role') ?? '') : '';
  const label = t(role.labelKey);
  return (
    <li className={chosen && chosen !== role.key ? 'opacity-50' : ''}>
      <button type="submit" name="role" value={role.key} disabled={pending} aria-label={t('core.roles.signInAs', { role: label })} className={TILE}>
        <Preview name={role.key} label={label} phone={role.icon === 'pharmacy'} />
        <TileBody icon={ICONS[role.icon]} label={label} hint={t(role.hintKey)} />
      </button>
    </li>
  );
}

function Groups() {
  const { pending } = useFormStatus();
  return (
    <div className="flex flex-col gap-8" aria-busy={pending}>
      {GROUPS.map((group) => {
        const roles = DEMO_ROLES.filter((r) => r.group === group);
        return (
          <section key={group} aria-labelledby={`groupe-${group}`} className="flex flex-col gap-3">
            <div className="flex flex-wrap items-baseline gap-x-3 gap-y-0.5">
              <h3 id={`groupe-${group}`} className="text-lg font-semibold text-ink">
                {t(`core.home.roleGroups.${group}`)}
              </h3>
              <p className="text-sm text-ink-muted">{t(`core.home.roleGroupHints.${group}`)}</p>
            </div>
            <ul className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
              {group === 'public' ? (
                <li>
                  <Link href="/medicaments" className={TILE}>
                    <Preview name="public" label={t('core.home.publicRole.label')} phone />
                    <TileBody icon={ICONS.public} label={t('core.home.publicRole.label')} hint={t('core.home.publicRole.hint')} />
                  </Link>
                </li>
              ) : null}
              {roles.map((role) => (
                <RoleTile key={role.key} role={role} />
              ))}
            </ul>
          </section>
        );
      })}
    </div>
  );
}

export function RolePicker() {
  return (
    <form action={signInAsDemoRole}>
      <Groups />
    </form>
  );
}
